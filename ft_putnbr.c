#include "ft_printf.h"

int	ft_putnbr(int n)
{
	int		c;
	long	nb;

	nb = n;
	c = 0;
	if (nb < 0)
	{
		write(1, "-", 1);
		nb *= -1;
		c++;
	}
	if (nb >= 10)
		c += ft_putnbr(nb / 10);
	c += ft_putchar((nb % 10) + '0');
	return (c);
}
